#!/usr/bin/env python
"""Write reports/errp_bench/RESULTS.txt: measured results (from generated/results_summary.txt and the generated
tables) followed by the planned experiments with their PROJECTED numbers (marked tbd), converted from
paper/errp_bench/sections/extended.tex so that txt and LaTeX can never disagree.

  python bench/make_report_txt.py
"""
import re
from pathlib import Path

P = Path(__file__).resolve().parents[1] / "paper/errp_bench"
OUT = Path(__file__).resolve().parents[1] / "reports/errp_bench/RESULTS.txt"


def macros():
    m = {}
    for line in (P / "generated/numbers.tex").read_text().splitlines():
        r = re.match(r"\\newcommand\{\\(\w+)\}\{(.*)\}$", line)
        if r:
            m[r.group(1)] = r.group(2)
    return m


def detex(s, M):
    s = re.sub(r"\\tbdv\{([^{}]*(?:\{[^{}]*\}[^{}]*)*)\}", r"\1 (tbd)", s)
    s = re.sub(r"\\(\w+)\{\}", lambda r: M.get(r.group(1), r.group(0)), s)
    s = re.sub(r"\\scriptsize\{\$\\pm\$([^}]*)\}", r" ± \1", s)
    s = re.sub(r"\\scriptsize\{\$\^\{\\ast\}\$\}", "*", s)
    s = re.sub(r"\\textbf\{([^{}]*)\}", r"\1", s)
    s = re.sub(r"\\multicolumn\{\d+\}\{\w\}\{([^{}]*)\}", r"\1", s)
    s = re.sub(r"~?\\(cite|ref)p?\{[^}]*\}", "", s)
    for a, b in [("$-$", "-"), ("$+$", "+"), ("$", ""), ("\\checkmark", "EA"), ("\\,", " "), ("\\ ", " "),
                 ("\\Delta", "Delta"), ("\\geq", ">="), ("^{\\dagger}", "+"), ("^{\\ast}", "*"), ("\\pm", "±"),
                 ("A^\\star", "A*"), ("\\times10^{", "e"), ("{", ""), ("}", ""), ("\\%", "%")]:
        s = s.replace(a, b)
    return s


def balanced(s, i):
    """Content of the {...} group starting at s[i] == '{'."""
    depth = 0
    for j in range(i, len(s)):
        depth += {"{": 1, "}": -1}.get(s[j], 0)
        if depth == 0:
            return s[i + 1:j]
    return s[i + 1:]


def tables_as_text(tex, M):
    out = []
    envs = re.findall(r"\\begin\{table\}.*?\\end\{table\}", tex, re.S) or [tex]
    for env in envs:
        k = env.find("\\caption{")
        cap = balanced(env, k + len("\\caption")) if k >= 0 else ""
        out.append("TABLE: " + " ".join(detex(cap, M).split()))
        for body in re.findall(r"\\begin\{tabular\}.*?\\end\{tabular\}", env, re.S):
            for row in re.split(r"\\\\", body):
                row = re.sub(r"\\(begin|end)\{tabular\}(\{[^}]*\})?|\\(top|mid|bottom)rule", "", row).strip()
                if row:
                    out.append("  " + " | ".join(c.strip() for c in detex(row, M).split("&")))
            out.append("")
    return out


def main():
    M = macros()
    L = ["ErrP-Bench / ErrP-Ens: results (publication format)", "=" * 60, "",
         "PART A. MEASURED RESULTS (every number below was measured; generated by bench/make_paper.py)", ""]
    L += (P / "generated/results_summary.txt").read_text().splitlines()
    L += ["", "Main and supporting tables (measured):", ""]
    for name, cap in [("table_main", "Cross-subject decoding, macro-participant AUROC (mean ± SD over seeds; * one seed)"),
                      ("table_ea", "EA effect (AUROC with EA minus without; * p<0.05 uncorrected)"),
                      ("table_fm", "Best foundation vs best compact"), ("table_bvo", "Best variant vs others (Holm)"),
                      ("table_rl", "RL frontier: normalized success AUC and paired gain vs sparse"),
                      ("table_datasets", "Datasets")]:
        f = P / f"generated/{name}.tex"
        if f.exists():
            L += tables_as_text(f"\\begin{{table}}\\caption{{{cap}}}\n" + f.read_text() + "\\end{table}", M)
    L += ["", "PART B. PLANNED EXPERIMENTS -- PROJECTED NUMBERS, NOT MEASURED", "",
          "Every value followed by (tbd) is a projection to be replaced by a measurement. Values without (tbd) in",
          "these tables are measured and repeat Part A.", ""]
    L += tables_as_text((P / "sections/extended.tex").read_text(), M)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(L) + "\n")
    print("wrote", OUT, len(L), "lines")


if __name__ == "__main__":
    main()
