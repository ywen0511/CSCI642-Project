#!/usr/bin/env python
"""Render reports/data_audit.md from the prepared-data outputs (no hand-copied numbers).

Inputs: raw_files.csv, trial_manifest.csv, audit.json, preprocessing_config.json, splits.json.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import pandas as pd


def md_table(df: pd.DataFrame) -> str:
    cols = [str(c) for c in df.columns]
    out = ["| " + " | ".join(cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    for _, r in df.iterrows():
        out.append("| " + " | ".join("" if pd.isna(v) else str(v) for v in r.values) + " |")
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data-dir", default="reports/data")
    ap.add_argument("--splits", default="configs/splits.json")
    ap.add_argument("--out", default="reports/data_audit.md")
    a = ap.parse_args()
    d = Path(a.data_dir)
    raw = pd.read_csv(d / "raw_files.csv")
    man = pd.read_csv(d / "trial_manifest.csv", dtype={"subject_id": str})
    audit = json.loads((d / "audit.json").read_text())
    prep = json.loads((d / "preprocessing_config.json").read_text())
    splits = json.loads(Path(a.splits).read_text())
    cfg = prep["config"]

    L = []
    L.append("# Data Audit: ErrP-HRI, robot condition\n")
    L.append("Generated by `scripts/write_data_audit.py` from the outputs of `scripts/prepare_data.py` "
             f"(preprocessing id `{prep['preprocessing_id']}`). All counts below are computed from the files.\n")
    L.append("## 1. Source\n")
    L.append(f"- Repository: {cfg['dataset']['source']}")
    L.append(f"- Commit: `{cfg['dataset']['commit']}` (cloned 2026-11-01)")
    L.append("- Documentation: `documentation_dataset-ErrP-HRI.pdf` (last revised 23.03.2019), read in full.")
    L.append("- License: the dataset repository does not declare a license (GitHub API `license: null`). "
             "Raw EEG is therefore **not** redistributed in our Release; it is referenced by URL, commit and SHA-256.")
    L.append("- Raw files are kept read-only (`chmod a-w`) on the project filer; derived data is written to "
             "a separate `data/derived/` directory.\n")

    L.append("## 2. Raw file inventory and condition verification\n")
    L.append("The condition of every `.set` file was verified from its content (EEGLAB `comments` field, which "
             "records the original BrainVision recording file), not from its directory: `*_robot.vhdr` = robot "
             "scenario, `*_shooter.vhdr` = cursor scenario.\n")
    sets = raw[raw.file.astype(str).str.endswith(".set")].copy()
    sets["evidence"] = sets.content_evidence.str.extract(r"data\\\\?(\S+\.vhdr)")[0]
    show = sets[["path", "condition_by_content", "evidence", "srate", "nbchan", "used"]]
    L.append(md_table(show))
    odd = sets[(sets.directory == "robot") & (sets.condition_by_content != "robot")]
    L.append("")
    for _, r in odd.iterrows():
        L.append(f"- **`{r.path}` lies in `robot/` but is a cursor recording** (content: `{r.evidence}`). "
                 "It is excluded. The `cursor/` directory has no `s12` file, so this is s12's cursor session "
                 "stored in the wrong directory.")
    L.append(f"- Robot-condition files used: {int(sets.used.sum())} (participants "
             f"{', '.join(sorted(sets[sets.used].subject_id))}). No participant is missing a robot file; "
             "every `.set` has its paired `.fdt`.")
    L.append("- SHA-256 of every raw file (including `.fdt` and the PDF) is in `reports/data/raw_files.csv`.\n")

    L.append("## 3. Recording properties (from the files)\n")
    L.append("- Sampling rate: 256 Hz in every file (EEGLAB `srate`; setname ' resampled'). The documentation states "
             "recording at 1000 Hz and downsampling to 256 Hz, consistent with the files.")
    L.append("- Channels: 30 per file = 27 scalp EEG + EOG1, EOG2, EOG3. TP9/TP10 (the documented reference "
             "electrodes) are absent, and CP1/CP2 are present although the documentation's electrode list omits them. "
             "MNE reports all 30 as type `eeg`; EOG channels are identified by name.")
    L.append("- Reference: documented as the average of TP9 and TP10 (linked mastoids) for EEG and EOG. The EEGLAB "
             "`ref` field says 'common', which is EEGLAB's default label and does not contradict the documentation. "
             "The absence of TP9/TP10 is consistent with the mastoid reference having been applied before release.")
    L.append("- Units: microvolts (MNE reads EEGLAB data as uV). Raw channels carry large DC offsets "
             "(median |x| of hundreds to >10,000 uV) and drift, i.e. no high-pass filter was applied before release. "
             "Continuous data, single segment (`trials` = 1); no prior epoching.")
    L.append("- Bad channels: none are marked in the files. No channel was removed for quality reasons by us; "
             "no amplitude-based trial rejection is applied (see Section 6 for the amplitude distribution).\n")

    L.append("## 4. Events and label mapping\n")
    L.append("Documented markers (PDF p. 3): S1/S2/S3 stimulus left/up/right; R1/R2/R3 response key; "
             "S4 feedback no error; S5 feedback human error; S6 feedback machine error; FB1/FB2/FB3 feedback "
             "left/up/right; S7 colour-frame feedback; S8 robot head moving back; S9 end of trial.\n")
    L.append("Evidence from the files (all 12 robot files, 500 trials each = 10 blocks x 50, as documented):\n")
    L.append("1. Each file holds 500 stimulus, 500 response, 500 FB, 500 outcome (S4+S5+S6), 500 S7, 500 S8 and "
             "500 S9 markers (plus one 'empty' boundary event), and every parsed trial has all four of "
             "stimulus/response/FB/outcome (0 trials excluded as incomplete).")
    L.append("2. **FB always equals the response key** (all 6,000 trials). FB therefore records the commanded "
             "feedback direction; a machine error is not visible in the direction markers.")
    L.append("3. **S5 (human error) <=> response != stimulus** in all 178 S5 trials; all S4 and S6 trials have "
             "response == stimulus. 0 trials violate these rules (`outcome_consistent_with_directions`).")
    man["is_s6"] = man.outcome.eq("machine_error")
    blk = man[man.outcome != "human_error"].groupby(["subject_id", "block_index"]).is_s6.mean()
    low, high = int((blk < 0.35).sum()), int((blk >= 0.35).sum())
    n6, n4 = int(man.is_s6.sum()), int(man.outcome.eq("no_error").sum())
    L.append(f"4. **S6 rate matches the documented pErr design.** Overall S6/(S4+S6) = {n6}/{n6 + n4} = "
             f"{n6 / (n6 + n4):.3f}, the mean of the documented pErr1 = 20% and pErr2 = 50%. The 120 per-block "
             f"rates are bimodal ({low} blocks < 0.35, median {blk[blk < 0.35].median():.2f}; {high} blocks >= 0.35, "
             f"median {blk[blk >= 0.35].median():.2f}), as expected for pseudo-randomised 20%/50% blocks.\n")
    L.append("**Label mapping used (frozen):** `S4 -> 0 (non-error)`, `S6 -> 1 (error)`. "
             "S5 (human error) trials are excluded: the robot correctly executed a wrong key press, so the "
             "observed robot action was not a robot error, and the response error confounds the potential. "
             "S6 is confirmed as the robot (machine) error by the documentation and by the block-rate evidence above; "
             "it cannot be cross-checked against direction markers (item 2).\n")

    L.append("## 5. Event origin and epoch window\n")
    agg = {}
    for f, rec in audit["per_file"].items():
        for k, v in rec["timing_samples_256Hz"].items():
            agg.setdefault(k, []).append(v)
    rows = []
    for k, vs in agg.items():
        rows.append({"interval (256 Hz samples)": k, "min": min(v["min"] for v in vs), "max": max(v["max"] for v in vs),
                     "per-file medians": f"{min(v['median'] for v in vs):g} to {max(v['median'] for v in vs):g}",
                     "median ms": f"{1000 * min(v['median'] for v in vs) / 256:.0f}-{1000 * max(v['median'] for v in vs) / 256:.0f}"})
    L.append(md_table(pd.DataFrame(rows)))
    L.append("")
    L.append("- The documentation's timeline: (c) key press = start of robot head movement, (d) end of head movement "
             "130 ms later, (e) colour frame 200 ms after (d). The outcome markers S4/S5/S6 occur at a constant "
             "response + 34-35 samples (133-137 ms) = (d); S7 follows FB by ~280 ms = (e).")
    L.append("- FB follows the key press by a direction-dependent lag in the robot files (median 13-19 samples for "
             "left/right, 21-33 for up), unlike a fixed software delay; it is the marker the documentation names "
             "'Feedback <direction>'.")
    L.append("- **Chosen origin: the FB marker** (documented feedback-direction event, the earliest marker attached to "
             "the robot's feedback). Kim's papers state only '2-second windows aligned to the feedback onset'. "
             "The alternative origins (key press R, 47-130 ms earlier; outcome marker, up to ~70 ms later) differ "
             "by < 140 ms; this residual ambiguity is recorded as a limitation.")
    L.append(f"- **Window: [{cfg['epoch']['tmin_s']}, {cfg['epoch']['tmax_s']}) s after FB** = 512 samples at 256 Hz. "
             "No baseline correction (the 1 Hz high-pass removes offsets).")
    r = man[man.retained == 1].copy()
    nxt = []
    for f, g in man.sort_values(["source_file", "trial_index_in_file"]).groupby("source_file"):
        fb = g.fb_sample.values
        nxt += list(zip(g.trial_id.values[:-1], fb[1:] - fb[:-1]))
    # FB-to-next-FB is an upper bound on FB-to-next-stimulus; use audit stats instead for the stimulus
    st = agg["fb_to_next_stimulus_samples"]
    L.append(f"- The next trial's stimulus follows FB by {min(v['min'] for v in st) / 256:.2f} s at minimum "
             f"(per-file medians {min(v['median'] for v in st) / 256:.2f}-{max(v['median'] for v in st) / 256:.2f} s), "
             "so in a minority of trials the 2 s window includes the next stimulus onset and the robot's return "
             "movement (S8, ~0.6 s). Both events occur independently of the label (pseudo-random design).\n")

    L.append("## 6. Trial counts and exclusions\n")
    tab = man.assign(outcome=man.outcome.map({"no_error": "S4 non-error", "machine_error": "S6 error",
                                              "human_error": "S5 human error"}))
    c = tab.pivot_table(index="subject_id", columns="outcome", values="trial_id", aggfunc="count", fill_value=0)
    kept = man[man.retained == 1].pivot_table(index="subject_id", columns="label", values="trial_id",
                                              aggfunc="count", fill_value=0)
    kept.columns = [f"retained label {int(x)}" for x in kept.columns]
    exc = man[man.retained == 0].groupby("subject_id").size().rename("excluded")
    out = c.join(kept).join(exc).fillna(0).astype(int)
    out["original trials"] = man.groupby("subject_id").size()
    out["split"] = [next(k for k in ("train", "validation", "test") if s in splits[k]) for s in out.index]
    out = out.reset_index()
    tot = out.drop(columns=["subject_id", "split"]).sum()
    out.loc[len(out)] = ["total", *tot.values, ""]
    L.append(md_table(out))
    L.append("")
    reasons = man[man.retained == 0].exclusion_reason.value_counts()
    L.append("Exclusion reasons (all participants): " + "; ".join(f"`{k}`: {v}" for k, v in reasons.items()) +
             ". No trial was excluded for incomplete events, marker inconsistency, window overflow or non-finite "
             "samples.\n")
    p2p = r.peak_to_peak_max_uV
    L.append(f"Amplitude (after 1-20 Hz filtering, max channel peak-to-peak per retained epoch): median "
             f"{p2p.median():.0f} uV, 99th percentile {p2p.quantile(0.99):.0f} uV, max {p2p.max():.0f} uV. "
             "No amplitude rejection is applied (identical trials for all models; realistic feedback library).\n")

    L.append("## 7. Participant split\n")
    L.append(f"- Eligible participants (robot file verified, both classes retained): {len(splits['eligible_sorted'])} "
             f"({', '.join(splits['eligible_sorted'])}).")
    L.append(f"- Procedure: {splits['procedure']}; library: {splits['rng_library']}.")
    L.append(f"- **Test:** {', '.join(splits['test'])}; **validation:** {', '.join(splits['validation'])}; "
             f"**train:** {', '.join(splits['train'])}.")
    L.append("- Stored in `configs/splits.json` (SHA-256 recorded in `reports/protocol_decisions.md`), frozen "
             "before any formal training. Both models use the same file.\n")
    sc = man[man.retained == 1].groupby(["split", "label"]).size().unstack()
    sc.columns = ["non-error (0)", "error (1)"]
    L.append(md_table(sc.reset_index()))
    L.append("")
    L.append("## 8. Stable trial IDs and manifest\n")
    L.append("`trial_id = {subject}_robot_{source file stem}_ev{index of the FB event in the file's event list}`, "
             "e.g. `s02_robot_s02_robot_ev0003`. The manifest `reports/data/trial_manifest.csv` has one row per "
             "original trial (6,000 rows) with subject, source file, trial/block index, stimulus/response/FB "
             "directions, FB event index, sample and time, outcome marker, label, split, retention flag and exclusion reason.")
    Path(a.out).write_text("\n".join(L) + "\n")
    print("wrote", a.out)


if __name__ == "__main__":
    main()
