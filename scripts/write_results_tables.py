#!/usr/bin/env python
"""Render the measured tables of reports/eeg_results.md (written to reports/generated/results_tables.md)
from artifacts/metrics_summary.json, artifacts/selection/*.json and the run directories."""
from __future__ import annotations

import argparse
import json
import statistics as stats
from pathlib import Path


def f(x, d=3):
    if x is None or (isinstance(x, float) and x != x):
        return "n/a"
    return f"{x:.{d}f}"


def table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def run_timing(rd: Path) -> dict:
    log = [json.loads(l) for l in (rd / "train_log.jsonl").read_text().splitlines()] if (rd / "train_log.jsonl").exists() else []
    if not log:
        rc = json.loads((rd / "run_config.json").read_text())
        return {"epochs": "n/a", "train_s": rc.get("fit_time_s"), "s_per_epoch": None, "peak_mem_mb": None}
    t = [h["epoch_time_s"] for h in log]
    return {"epochs": len(log), "train_s": sum(t), "s_per_epoch": stats.median(t),
            "peak_mem_mb": max((h["peak_gpu_mem_mb"] or 0) for h in log),
            "sps": stats.median(h["train_samples_per_s"] for h in log)}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--artifacts", required=True)
    ap.add_argument("--out", default="reports/generated/results_tables.md")
    a = ap.parse_args()
    art = Path(a.artifacts)
    ms = json.loads((art / "metrics_summary.json").read_text())
    sel = {m: json.loads((art / "selection" / f"{m}.json").read_text()) for m in ["eegnet", "cbramod"]}
    L = ["<!-- generated by scripts/write_results_tables.py; do not edit by hand -->\n"]
    main = {v["model"]: (k, v) for k, v in ms.items() if v["group"] == "main"}

    L.append("### Main comparison: pooled test set (participants s02, s08, s09)\n")
    rows = []
    for m in ["eegnet", "cbramod"]:
        rid, v = main[m]
        raw, cal, yd = v["test_pooled"]["raw@0.5"], v["test_pooled"]["calibrated@0.5"], v["test_pooled"]["calibrated@val_youden"]
        rows.append([m, rid, cal["n"], f"{cal['n_pos']}/{cal['n_neg']}", f(cal["auroc"]), f(cal["balanced_accuracy"]),
                     f(raw["brier"]), f(cal["brier"]), f(raw["nll"]), f(cal["nll"]), f(raw["ece_10bin"]), f(cal["ece_10bin"]),
                     f(v["temperature"], 3)])
    L.append(table(["model", "run", "n", "error/non-error", "AUROC", "bal. acc @0.5", "Brier raw", "Brier cal.",
                    "NLL raw", "NLL cal.", "ECE raw", "ECE cal.", "T"], rows))
    L.append("\nAUROC and balanced accuracy at 0.5 are identical for raw and calibrated probabilities "
             "(temperature scaling preserves order and the sign of the margin).\n")

    L.append("### Confusion matrices (test, P(error) >= 0.5) and validation-selected thresholds\n")
    rows = []
    for m in ["eegnet", "cbramod"]:
        rid, v = main[m]
        cal, yd = v["test_pooled"]["calibrated@0.5"], v["test_pooled"]["calibrated@val_youden"]
        cm, cmy = cal["confusion_matrix"], yd["confusion_matrix"]
        rows.append([m, f"TN {cm['tn']} / FP {cm['fp']} / FN {cm['fn']} / TP {cm['tp']}", f(cal["sensitivity_tpr"]),
                     f(cal["specificity_tnr"]), f(v["val_youden_threshold"], 4), f(yd["balanced_accuracy"]),
                     f"TN {cmy['tn']} / FP {cmy['fp']} / FN {cmy['fn']} / TP {cmy['tp']}"])
    L.append(table(["model", "confusion @0.5", "sensitivity", "specificity", "val-selected threshold (Youden)",
                    "test bal. acc @ that threshold", "confusion @ that threshold"], rows))
    L.append("")

    L.append("### Per test participant (calibrated, threshold 0.5)\n")
    rows = []
    for m in ["eegnet", "cbramod"]:
        rid, v = main[m]
        for r in v["test_per_subject_calibrated@0.5"]:
            rows.append([m, r["subject_id"], r["n"], f"{r['n_pos']}/{r['n_neg']}", f(r["auroc"]), f(r["balanced_accuracy"]),
                         f(r["brier"]), r["auroc_note"] or ""])
        mac = v["test_subject_macro_calibrated@0.5"]
        rows.append([m, "**macro (3 participants, unweighted)**", "", "", f(mac["auroc"]), f(mac["balanced_accuracy"]),
                     f(mac["brier"]), ""])
    L.append(table(["model", "participant", "n", "error/non-error", "AUROC", "bal. acc", "Brier (cal.)", "note"], rows))
    L.append("")

    L.append("### Validation-based selection (search budget: 2 candidates per model)\n")
    rows = []
    for m in ["eegnet", "cbramod"]:
        for c in sel[m]["candidates"]:
            rows.append([m, c["run_id"], " ".join(c["overrides"]), f(c["best_val_auroc"]), c["best_epoch"],
                         c["epochs_completed"], "yes" if c["stopped_early"] else "no",
                         "**selected**" if c["run_id"] == sel[m]["selected_run_id"] else ""])
    L.append(table(["model", "run", "setting", "best val AUROC", "best epoch", "epochs run", "early stop", ""], rows))
    L.append("\nValidation scores were used for selection, early stopping and calibration and are optimistic.\n")

    L.append("### Calibration (fitted on validation)\n")
    rows = []
    for m in ["eegnet", "cbramod"]:
        rid, v = main[m]
        vr, vc = v["validation"]["raw@0.5"], v["validation"]["calibrated@0.5"]
        rows.append([m, f(v["temperature"]), f(vr["nll"]), f(vc["nll"]), f(vr["brier"]), f(vc["brier"]),
                     f(vr["mean_p_error"]), f(vc["mean_p_error"]), f(vr["n_pos"] / vr["n"])])
    L.append(table(["model", "temperature T", "val NLL raw", "val NLL cal.", "val Brier raw", "val Brier cal.",
                    "val mean p raw", "val mean p cal.", "val error rate"], rows))
    L.append("")

    seeds = [(k, v) for k, v in ms.items() if v["group"] in ("main", "additional_seeds")]
    if any(v["group"] == "additional_seeds" for _, v in seeds):
        L.append("### Decoder-seed variability (selected configuration, seeds 42-46; test, calibrated)\n")
        rows = []
        for m in ["eegnet", "cbramod"]:
            vs = sorted([(v["decoder_seed"], v) for k, v in seeds if v["model"] == m], key=lambda t: t[0])
            for s, v in vs:
                c = v["test_pooled"]["calibrated@0.5"]
                rows.append([m, s, f(c["auroc"]), f(c["balanced_accuracy"]), f(c["brier"]),
                             f(v["test_subject_macro_calibrated@0.5"]["auroc"])])
            for key, name in [("auroc", "AUROC"), ("balanced_accuracy", "bal. acc"), ("brier", "Brier")]:
                pass
            au = [v["test_pooled"]["calibrated@0.5"]["auroc"] for _, v in vs]
            ba = [v["test_pooled"]["calibrated@0.5"]["balanced_accuracy"] for _, v in vs]
            br = [v["test_pooled"]["calibrated@0.5"]["brier"] for _, v in vs]
            ma = [v["test_subject_macro_calibrated@0.5"]["auroc"] for _, v in vs]
            rows.append([f"**{m} mean ± sd (n={len(vs)})**", "",
                         f"{f(stats.mean(au))} ± {f(stats.stdev(au))}", f"{f(stats.mean(ba))} ± {f(stats.stdev(ba))}",
                         f"{f(stats.mean(br))} ± {f(stats.stdev(br))}", f"{f(stats.mean(ma))} ± {f(stats.stdev(ma))}"])
        L.append(table(["model", "decoder seed", "pooled AUROC", "bal. acc @0.5", "Brier", "participant-macro AUROC"], rows))
        L.append("\nSeed 42 is the formal run in the feedback library; seeds 43-46 reuse the selected setting and are "
                 "reported only to show decoder-training variability (sd over 5 seeds; the same 3 test participants).\n")

    sup = [(k, v) for k, v in ms.items() if v["group"] == "supplementary"]
    if sup:
        L.append("### Supplementary baselines (same split, trials, windows and evaluation; one run each, no tuning)\n")
        rows = []
        for k, v in sorted(sup, key=lambda kv: -kv[1]["test_pooled"]["calibrated@0.5"]["auroc"]):
            c, r = v["test_pooled"]["calibrated@0.5"], v["test_pooled"]["raw@0.5"]
            vauc = v["validation"]["raw@0.5"]["auroc"]
            rows.append([v["model"], k, f(vauc), f(c["auroc"]), f(c["balanced_accuracy"]), f(r["brier"]), f(c["brier"]),
                         f(v["test_subject_macro_calibrated@0.5"]["auroc"])])
        for m in ["eegnet", "cbramod"]:
            rid, v = main[m]
            c, r = v["test_pooled"]["calibrated@0.5"], v["test_pooled"]["raw@0.5"]
            rows.append([f"*{m} (main, for reference)*", rid, f(v["validation"]["raw@0.5"]["auroc"]), f(c["auroc"]),
                         f(c["balanced_accuracy"]), f(r["brier"]), f(c["brier"]),
                         f(v["test_subject_macro_calibrated@0.5"]["auroc"])])
        L.append(table(["model", "run", "val AUROC", "test AUROC", "test bal. acc @0.5", "Brier raw", "Brier cal.",
                        "participant-macro AUROC"], rows))
        L.append("")

    L.append("### Training cost (measured)\n")
    rows = []
    for rd in sorted((art / "runs").iterdir()):
        if not rd.is_dir():
            continue
        t = run_timing(rd)
        s = json.loads((rd / "train_summary.json").read_text()) if (rd / "train_summary.json").exists() else {}
        rows.append([rd.name, t["epochs"], f(t["s_per_epoch"], 2), f(t["train_s"], 1), f(t.get("peak_mem_mb"), 0),
                     s.get("n_params", "")])
    L.append(table(["run", "epochs", "median s/epoch", "total epoch time (s)", "peak GPU MB", "params"], rows))
    L.append("\nEpoch time includes the validation pass; checkpoint writes to the NFS filer are excluded.\n")
    Path(a.out).parent.mkdir(parents=True, exist_ok=True)
    Path(a.out).write_text("\n".join(L) + "\n")
    print("wrote", a.out)


if __name__ == "__main__":
    main()
