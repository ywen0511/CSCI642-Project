#!/usr/bin/env python
"""Generate every results table and figure of the decoder study from committed sources, plus a number audit.

Usage: python scripts/decoder_improvement/make_report_tables.py --dec reports/decoder_improvement/decisions \
          --test reports/decoder_improvement/results/test --out reports/decoder_improvement/results/generated

Writes results_tables.md (all tables), figure PNG/PDF files with their source CSVs, and number_audit.json: for every
table cell, the value as printed and its source file + selector, so `verify_numbers` can recompute it.
"""
import argparse
import json
import statistics
from pathlib import Path

import numpy as np
import pandas as pd

HIST = {  # historical archived EEG results (reports/eeg_results.md, Sections 3-4; Release eeg-stage1-20261101-bccbb8a)
    "eegnet": {"seed42_auroc": 0.637, "five_seed_auroc": (0.613, 0.016), "five_seed_bacc": (0.577, 0.012),
               "five_seed_brier_cal": (0.238, 0.006)},
    "cbramod": {"seed42_auroc": 0.573, "five_seed_auroc": (0.568, 0.007), "five_seed_bacc": (0.546, 0.010),
                "five_seed_brier_cal": (0.245, 0.004)},
}


class Audit:
    def __init__(self):
        self.items = []

    def v(self, value, source, selector, fmt="{:.3f}"):
        s = fmt.format(value)
        self.items.append({"printed": s, "fmt": fmt, "value": float(value), "source": source, "selector": selector})
        return s


def table(header, rows):
    return ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)] + ["| " + " | ".join(map(str, r)) + " |" for r in rows]


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--dec", required=True)
    ap.add_argument("--test", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    dec, test, out = Path(a.dec), Path(a.test), Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    A = Audit()
    L = ["# Decoder-improvement study: generated tables", "",
         "Generated by `scripts/decoder_improvement/make_report_tables.py`; every value is listed with its source in "
         "`number_audit.json`. CV score = mean over the 7 inner-validation participants of the seed-mean AUROC "
         "(train-only participants s03-s07, s10, s12). Test = previously evaluated outer test participants s02, s08, s09.", ""]
    # ---------------- CV stages
    for st, title in (("A", "Stage A: CBraMod head x adaptation (1-20 Hz, weighted CE, seeds 42-44, 3 folds)"),
                      ("C", "Stage C: EEGNet learning rate x dropout (1-20 Hz)"),
                      ("D", "Stage D: band comparison for the selected recipes"),
                      ("E", "Stage E: loss comparison (weighted vs unweighted cross-entropy)")):
        d = json.loads((dec / f"stage_{st}.json").read_text())
        src = f"reports/decoder_improvement/decisions/stage_{st}.json"
        rows = []
        for i, c in enumerate(sorted(d["candidates"], key=lambda c: -c["score"])):
            r = c["recipe"]
            k = d["candidates"].index(c)
            desc = (f"{r.get('head', '')} / {r.get('adaptation', '')} / bb {r.get('backbone_lr')}" if r["arch"] == "cbramod"
                    else f"lr {r['lr']} / dropout {r['dropout']}") + f" / {r['band']} Hz / {r['loss']}"
            rows.append([f"`{c['candidate_id']}`", desc, c["params_trainable"],
                         A.v(c["score"], src, f"candidates[{k}].score", "{:.4f}"),
                         A.v(c["cv_pooled_auroc"], src, f"candidates[{k}].cv_pooled_auroc", "{:.4f}"),
                         A.v(c["cv_brier"], src, f"candidates[{k}].cv_brier", "{:.4f}"),
                         A.v(c["cv_nll"], src, f"candidates[{k}].cv_nll", "{:.4f}"),
                         A.v(c["cv_mean_p_label1"] - c["cv_mean_p_label0"], src,
                             f"candidates[{k}].cv_mean_p_label1-cv_mean_p_label0", "{:.4f}"),
                         c["median_best_epoch"]])
        L += [f"## {title}", ""] + table(["candidate", "recipe", "trainable params", "CV score", "pooled AUROC",
                                          "Brier (raw)", "NLL (raw)", "p gap (err-nonerr)", "median best epoch"], rows)
        w = d.get("winner") or d.get("winners")
        L += ["", f"Selected: {json.dumps({k: v['candidate_id'] for k, v in w.items()}) if 'winners' in d else w['candidate_id']}", ""]
        if st == "A":
            pd.DataFrame([{"candidate": c["candidate_id"], **c["per_participant_seed_mean"], "score": c["score"]}
                          for c in d["candidates"]]).to_csv(out / "stage_A_per_participant.csv", index=False)
    b = json.loads((dec / "stage_B.json").read_text())
    L += ["## Stage B: backbone learning-rate refinement", "", f"Skipped: {b['reason']}", ""]
    # ---------------- confirmation + freeze
    fz = json.loads((dec / "freeze.json").read_text())
    srcf = "reports/decoder_improvement/decisions/freeze.json"
    rows = []
    for k, r in enumerate(fz["recipes"]):
        rows.append([r["arch"], r["role"], f"`{r['candidate_id']}`", A.v(r["cv_score_5seed"], srcf, f"recipes[{k}].cv_score_5seed", "{:.4f}"),
                     A.v(r["cv_score_screening_seeds"], srcf, f"recipes[{k}].cv_score_screening_seeds", "{:.4f}"),
                     A.v(r["cv_score_new_seeds_45_46"], srcf, f"recipes[{k}].cv_score_new_seeds_45_46", "{:.4f}"),
                     r["final_epochs"], "yes" if r.get("identical_to_reference") else ""])
    L += ["## Stage F: five-seed confirmation and freeze", ""] + table(
        ["arch", "role", "candidate", "CV score (5 seeds)", "screening seeds 42-44", "new seeds 45-46",
         "final epochs (fixed)", "identical to reference"], rows)
    pc = fz["confirmation_paired_differences"]
    for arch, v in pc.items():
        if "pairs" in v:
            L += ["", f"{arch}: selected minus reference per participant and seed: mean "
                      f"{A.v(v['mean'], srcf, f'confirmation_paired_differences.{arch}.mean', '{:+.4f}')}, "
                      f"positive in {v['n_positive']} of {v['n']} pairs; selection optimism (screening minus new seeds) "
                      f"{A.v(v['selection_optimism_selected'], srcf, f'confirmation_paired_differences.{arch}.selection_optimism_selected', '{:+.4f}')}."]
        else:
            L += ["", f"{arch}: {v['note']}."]
    L.append("")
    # ---------------- calibration
    cal = json.loads((dec / "calibration.json").read_text())
    srcc = "reports/decoder_improvement/decisions/calibration.json"
    rows = []
    for arch, v in cal["deployment"].items():
        nll = v["selection"]["mean_heldout_participant_nll"]
        params = [m["params"] for m in v["per_model"].values()]
        prm = ", ".join(f"a={p['a']:.3f}, b={p['b']:+.3f}" if "a" in p else (f"T={p['T']:.3f}" if "T" in p else "-") for p in params)
        rows.append([arch, *(A.v(nll[m], srcc, f"deployment.{arch}.selection.mean_heldout_participant_nll.{m}", "{:.4f}")
                             for m in ("identity", "temperature", "affine")), v["method"], prm])
    L += ["## Calibration (validation participants s11/s13 only; committed before test access)", ""] + table(
        ["arch", "held-out NLL identity", "temperature", "affine", "selected", "per-seed parameters (seeds 42-46)"], rows)
    L += ["", "Controlled-comparison temperatures (per final model): " + ", ".join(
        f"{k.split('__')[0][:28]} s{k.split('__s')[1].split('__')[0]}: T={v['temperature']:.2f}" for k, v in cal["temperature_per_model"].items()), ""]
    # ---------------- test
    R = pd.read_csv(test / "test_metrics_per_model.csv")
    P = pd.read_csv(test / "test_metrics_per_participant.csv")
    srct = "reports/decoder_improvement/results/test/test_metrics_per_model.csv"
    rows = []
    for (arch, role), g in R.groupby(["arch", "role"], sort=False):
        def ms(kind, col):
            x = g[g.probability == kind][col]
            return (A.v(x.mean(), srct, f"mean({col}) where arch={arch},role={role},probability={kind}") + " ± " +
                    A.v(x.std(ddof=1), srct, f"sd({col}) where arch={arch},role={role},probability={kind}"))
        rows.append([arch, role, len(g[g.probability == "raw"]), ms("raw", "auroc"), ms("raw", "participant_macro_auroc"),
                     ms("raw", "balanced_accuracy"), ms("temperature", "balanced_accuracy"), ms("deployment", "balanced_accuracy"),
                     ms("raw", "brier"), ms("temperature", "brier"), ms("deployment", "brier"),
                     ms("temperature", "nll"), ms("deployment", "nll"), ms("temperature", "ece_10bin"), ms("deployment", "ece_10bin")])
    L += ["## Outer test (s02, s08, s09; 1,429 trials; five final refits per recipe; mean ± sample SD over seeds)", ""] + table(
        ["arch", "role", "seeds", "pooled AUROC", "participant-macro AUROC", "bal. acc @0.5 raw", "bal. acc temperature",
         "bal. acc deployment", "Brier raw", "Brier temperature", "Brier deployment", "NLL temperature", "NLL deployment",
         "ECE temperature", "ECE deployment"], rows)
    L += ["", "AUROC is identical for raw, temperature and deployment probabilities (monotone calibration). For the "
              "EEGNet row the selected recipe equals the historical reference recipe. Deployment = affine calibration "
              "(selected candidates); the CBraMod reference uses temperature for both.", ""]
    rows = []
    for (arch, role, part), g in P[P.probability == "raw"].groupby(["arch", "role", "participant"]):
        rows.append([arch, role, part, A.v(g.auroc.mean(), "reports/decoder_improvement/results/test/test_metrics_per_participant.csv",
                                           f"mean(auroc) where probability=raw,arch={arch},role={role},participant={part}"),
                     f"{g.auroc.std(ddof=1):.3f}", A.v(g.balanced_accuracy.mean(), "reports/decoder_improvement/results/test/test_metrics_per_participant.csv",
                                                        f"mean(balanced_accuracy) where probability=raw,arch={arch},role={role},participant={part}")])
    L += ["### Per participant (raw probabilities, mean over 5 seeds)", ""] + table(
        ["arch", "role", "participant", "AUROC", "SD over seeds", "bal. acc @0.5"], rows) + [""]
    pdiff = pd.read_csv(test / "test_paired_differences.csv")
    for arch, g in pdiff.groupby("arch"):
        L.append(f"Paired test differences, {arch} selected minus reference (same participants and seeds): mean "
                 f"{A.v(g.selected_minus_reference_auroc.mean(), 'reports/decoder_improvement/results/test/test_paired_differences.csv', f'mean(selected_minus_reference_auroc) where arch={arch}', '{:+.4f}')} AUROC, "
                 f"positive in {(g.selected_minus_reference_auroc > 0).sum()} of {len(g)} pairs.")
    L += ["", "### Historical archived results (Release eeg-stage1-20261101-bccbb8a; validation-selected historical runs, "
              "not controlled refits)", ""] + table(
        ["model", "seed-42 AUROC", "five-seed AUROC", "five-seed bal. acc", "five-seed calibrated Brier"],
        [[m, f"{h['seed42_auroc']:.3f}", f"{h['five_seed_auroc'][0]:.3f} ± {h['five_seed_auroc'][1]:.3f}",
          f"{h['five_seed_bacc'][0]:.3f} ± {h['five_seed_bacc'][1]:.3f}",
          f"{h['five_seed_brier_cal'][0]:.3f} ± {h['five_seed_brier_cal'][1]:.3f}"] for m, h in HIST.items()]) + [""]
    (out / "results_tables.md").write_text("\n".join(L) + "\n")
    (out / "number_audit.json").write_text(json.dumps({"n": len(A.items), "items": A.items}, indent=1) + "\n")
    # ---------------- figures
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    d = json.loads((dec / "stage_A.json").read_text())
    fig, ax = plt.subplots(figsize=(9, 4))
    cands = sorted(d["candidates"], key=lambda c: -c["score"])
    for i, c in enumerate(cands):
        vals = list(c["per_participant_seed_mean"].values())
        ax.scatter([i] * len(vals), vals, s=14, color="#999")
        ax.hlines(c["score"], i - 0.3, i + 0.3, color="k")
    ax.set_xticks(range(len(cands)))
    ax.set_xticklabels([c["candidate_id"] for c in cands], rotation=25, ha="right", fontsize=8)
    ax.set_ylabel("inner-validation AUROC\n(dots: participants; bar: macro score)")
    ax.axhline(0.5, color="r", lw=0.6, ls=":")
    ax.set_title("Stage A: CBraMod head x adaptation (train-only CV)")
    fig.tight_layout()
    fig.savefig(out / "fig_stage_A.png", dpi=150)
    fig.savefig(out / "fig_stage_A.pdf")
    plt.close(fig)
    raw = R[R.probability == "raw"]
    raw[["arch", "role", "seed", "auroc", "participant_macro_auroc"]].to_csv(out / "fig_test_auroc_source.csv", index=False)
    fig, ax = plt.subplots(figsize=(7, 4))
    groups = list(raw.groupby(["arch", "role"], sort=False))
    for i, ((arch, role), g) in enumerate(groups):
        ax.scatter([i] * len(g), g.auroc, color="tab:blue", s=18, label="seed (pooled)" if i == 0 else None)
        ax.hlines(g.auroc.mean(), i - 0.3, i + 0.3, color="k")
        h = HIST[arch]["five_seed_auroc"][0]
        ax.hlines(h, i - 0.3, i + 0.3, color="tab:red", ls="--", label="historical five-seed mean" if i == 0 else None)
    ax.set_xticks(range(len(groups)))
    ax.set_xticklabels([f"{a}\n{r}" for (a, r), _ in groups])
    ax.set_ylabel("test AUROC (s02, s08, s09)")
    ax.legend(fontsize=8)
    ax.set_title("Final refits: test AUROC per seed")
    fig.tight_layout()
    fig.savefig(out / "fig_test_auroc.png", dpi=150)
    fig.savefig(out / "fig_test_auroc.pdf")
    plt.close(fig)
    print("tables + figures written;", len(A.items), "audited numbers")


if __name__ == "__main__":
    main()
