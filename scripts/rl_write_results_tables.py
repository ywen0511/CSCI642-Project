#!/usr/bin/env python
"""Render markdown tables from rl.analysis outputs (no numbers are typed by hand).

Usage: python scripts/rl_write_results_tables.py --final reports/rl_v2_final --validation reports/rl_v2_validation \
          --out reports/rl_v2_final/results_tables.md
"""
import argparse
import csv
import json
import statistics
from collections import defaultdict
from pathlib import Path

ORDER = ["sparse", "dense", "eegnet", "cbramod", "ideal", "independent_eegnet", "independent_cbramod"]


def rows(path):
    with open(path, newline="") as f:
        return list(csv.DictReader(f))


def f(x, d=3):
    return "n/a" if x in ("", None) or x != x else f"{float(x):.{d}f}"


def condition_table(path):
    out = ["| condition | runs | final success | ever success | final distance (m) | sparse return | normalized AUC |",
           "|---|---|---|---|---|---|---|"]
    data = {r["condition"]: r for r in rows(path)}
    for c in ORDER:
        r = data[c]
        out.append(f"| {c} | {r['n_runs']} | {f(r['success_rate_mean'])} ± {f(r['success_rate_sd'])} | "
                   f"{f(r['ever_success_rate_mean'])} | {f(r['mean_final_distance_mean'], 4)} ± {f(r['mean_final_distance_sd'], 4)} | "
                   f"{f(r['mean_task_return_mean'], 2)} | {f(r['normalized_auc_success_mean'])} ± {f(r['normalized_auc_success_sd'])} |")
    return out


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--final", required=True)
    p.add_argument("--validation", required=True)
    p.add_argument("--out", required=True)
    a = p.parse_args()
    F, V = Path(a.final), Path(a.validation)
    L = ["# RL v2 generated result tables", "",
         "Generated by `scripts/rl_write_results_tables.py` from `rl.analysis` outputs. Shared controls: mean ± SD over",
         "RL seeds. EEG-assisted conditions: unweighted macro-average over participants of RL-seed means, ± SD over",
         "participants. Final-step success is the primary metric; AUC = normalized area under the success curve.", ""]
    L += ["## Final comparison (test participants s02, s08, s09; RL seeds 0-4; frozen EEG weight 1.0)", ""]
    L += condition_table(F / "by_condition.csv") + [""]
    L += ["### Per participant (mean ± SD over 5 RL seeds)", "",
          "| condition | participant | final success | final distance (m) | normalized AUC |", "|---|---|---|---|---|"]
    for r in rows(F / "by_condition_participant.csv"):
        L.append(f"| {r['condition']} | {r['subject']} | {f(r['success_rate_mean'])} ± {f(r['success_rate_sd'])} | "
                 f"{f(r['mean_final_distance_mean'], 4)} | {f(r['normalized_auc_success_mean'])} ± {f(r['normalized_auc_success_sd'])} |")
    L += ["", "### Paired differences (per participant and RL seed; shared controls matched by seed)", "",
          "| comparison | metric | pairs | mean difference | SD | first better / worse / equal |", "|---|---|---|---|---|---|"]
    g = defaultdict(list)
    for r in rows(F / "paired_differences.csv"):
        g[(r["a"], r["b"], r["metric"])].append(float(r["difference"]))
    for (x, y, m), v in g.items():
        pos, neg = sum(d > 0 for d in v), sum(d < 0 for d in v)
        L.append(f"| {x} - {y} | {m} | {len(v)} | {statistics.mean(v):+.3f} | {statistics.stdev(v):.3f} | "
                 f"{pos} / {neg} / {len(v) - pos - neg} |")
    L += ["", "### Feedback diagnostics during training (mean over runs)", "",
          "| condition | neutral fraction | error-label fraction | feedback events / episode | EEG reward per run | "
          "mean p_error (label 0 / 1) | AUROC of p_error vs label |", "|---|---|---|---|---|---|---|"]
    d = defaultdict(list)
    for r in rows(F / "feedback_diagnostics.csv"):
        d[r["condition"]].append(r)
    for c in ORDER:
        rs = d[c]

        def m(k):
            vals = [float(x[k]) for x in rs if x.get(k) not in ("", None)]
            return statistics.mean(vals) if vals else float("nan")
        L.append(f"| {c} | {f(m('neutral_fraction'))} | {f(m('error_label_fraction'))} | {f(m('events_per_episode'), 2)} | "
                 f"{f(m('eeg_reward_sum'), 0)} | {f(m('mean_p_error_label0'))} / {f(m('mean_p_error_label1'))} | {f(m('event_auroc'))} |")
    L += ["", "### Fixed decoder quality (test, calibrated p_error, threshold 0.5) vs RL outcome", "",
          "| condition | participant | decoder AUROC | decoder balanced accuracy | decoder Brier | RL final success | RL AUC |",
          "|---|---|---|---|---|---|---|"]
    for r in rows(F / "decoder_vs_rl.csv"):
        L.append(f"| {r['condition']} | {r['subject']} | {f(r['decoder_auroc'])} | {f(r['decoder_balanced_accuracy'])} | "
                 f"{f(r['decoder_brier'])} | {f(r['rl_success_mean'])} | {f(r['rl_auc_mean'])} |")
    L += ["", "## Validation candidates (participants s11, s13; RL seeds 100-102)", ""]
    for cand in sorted(p for p in V.iterdir() if p.is_dir()):
        w = json.loads((cand / "analysis.json").read_text())
        L += [f"### {cand.name}", ""] + condition_table(cand / "by_condition.csv") + [""]
    sel = V / "selection.md"
    if sel.exists():
        L += ["### Selection", "", sel.read_text().strip(), ""]
    Path(a.out).write_text("\n".join(L) + "\n")
    print(a.out)


if __name__ == "__main__":
    main()
